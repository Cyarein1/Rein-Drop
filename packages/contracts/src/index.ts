/**
 * Shared API contracts. Types here describe the wire format between
 * apps/api and its clients (web, mobile, worker). Keep them framework-free.
 */

/** Header carrying the request id. Clients may send one; the API always returns one. */
export const REQUEST_ID_HEADER = 'x-request-id';

// ---------------------------------------------------------------------------
// Health
// ---------------------------------------------------------------------------

/** `GET /health` - liveness. 200 whenever the process is serving requests; checks no dependencies. */
export interface HealthResponse {
  status: 'ok';
  service: 'api';
  /** ISO-8601 timestamp generated by the server. */
  timestamp: string;
}

export type DependencyStatus = 'up' | 'down';

/** `GET /ready` - readiness. HTTP 200 when ready, 503 (same body shape) when not. */
export interface ReadinessResponse {
  status: 'ready' | 'not_ready';
  checks: {
    database: DependencyStatus;
  };
  timestamp: string;
}

// ---------------------------------------------------------------------------
// Errors
// ---------------------------------------------------------------------------

export const API_ERROR_CODES = [
  'BAD_REQUEST',
  'VALIDATION_FAILED',
  'UNAUTHORIZED',
  'FORBIDDEN',
  'NOT_FOUND',
  'CONFLICT',
  'PAYLOAD_TOO_LARGE',
  'RATE_LIMITED',
  'NOT_IMPLEMENTED',
  'SERVICE_UNAVAILABLE',
  'INTERNAL_ERROR',
] as const;

export type ApiErrorCode = (typeof API_ERROR_CODES)[number];

/** One field-level problem, e.g. from request validation. */
export interface ApiErrorDetail {
  /** Dotted path into the request part, e.g. `body.criteria.maxPrice`. */
  path: string;
  message: string;
}

/** Body of every non-2xx API response (except `/ready`, which always returns ReadinessResponse). */
export interface ApiErrorBody {
  statusCode: number;
  code: ApiErrorCode;
  /** Safe to show to developers; never contains stack traces or secrets. */
  message: string;
  details?: ApiErrorDetail[];
  requestId?: string;
  path: string;
  timestamp: string;
}

export function isApiErrorBody(value: unknown): value is ApiErrorBody {
  if (typeof value !== 'object' || value === null) return false;
  const v = value as Record<string, unknown>;
  return (
    typeof v.statusCode === 'number' &&
    typeof v.code === 'string' &&
    (API_ERROR_CODES as readonly string[]).includes(v.code) &&
    typeof v.message === 'string'
  );
}
